"""Interfaces between the learning algorithms and an application.

An application provides a :class:`Problem` (a factory of episodes), the
episodes themselves (:class:`Episode`) and one or more experts
(:class:`Expert`). Actions are integers in ``range(problem.n_actions)``.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any, Protocol

import numpy as np


@dataclass
class Label:
    """Decision of an expert at a state.

    Attributes:
        action: Action the expert executes when it is in control.
        dist: Distribution over actions used as (soft) training target.
        solve_time: Time spent computing the label (seconds).
        gap: Largest relative optimality gap of the underlying solves.
    """

    action: int
    dist: np.ndarray
    solve_time: float = 0.0
    gap: float = 0.0


class Episode(Protocol):
    """One episode of an online decision problem.

    The learner calls :meth:`observe` at every decision epoch, possibly asks
    an expert for a label, then applies an action with :meth:`step`.
    """

    seed: int

    @property
    def done(self) -> bool:
        """Whether the episode is over."""

    def observe(self) -> Any:
        """Return the current (application-specific) state."""

    def features(self, state: Any) -> np.ndarray:
        """Return the feature vector of a state (float32)."""

    def mask(self, state: Any) -> np.ndarray:
        """Return the boolean feasibility mask over actions."""

    def step(self, action: int) -> None:
        """Apply a feasible action and move to the next decision epoch."""

    def info(self, state: Any) -> dict[str, float]:
        """Return extra per-state values stored with the labels."""

    def stats(self) -> dict[str, float]:
        """Return end-of-episode statistics, including ``"objective"``."""


class Problem(Protocol):
    """Factory of episodes.

    Attributes:
        n_actions: Number of actions.
        maximize: Whether the objective is maximised (else minimised).
    """

    n_actions: int
    maximize: bool

    def episode(self, seed: int) -> Episode:
        """Create the episode generated by ``seed``."""


class Expert(Protocol):
    """Expert queried for labels (and acting when it is in control)."""

    name: str

    def __call__(self, episode: Episode, state: Any, rng: np.random.Generator) -> Label:
        """Return the expert label of a state.

        The expert may use privileged information of the episode (for
        instance the realised future for a full-information expert).
        """


def one_hot(action: int, size: int) -> np.ndarray:
    """Return the one-hot distribution of an action."""
    dist = np.zeros(size)
    dist[action] = 1.0
    return dist


def aggregate_votes(
    votes: Sequence[int],
    size: int,
    rng: np.random.Generator | None = None,
    sample: bool = False,
) -> tuple[int, np.ndarray]:
    """Aggregate the actions of several expert solves.

    Args:
        votes: One action per solve (for instance one per scenario).
        size: Number of actions.
        rng: Generator used when ``sample`` is True.
        sample: Draw the executed action from the votes instead of taking
            the most frequent one.

    Returns:
        The executed action and the empirical distribution of the votes.

    Raises:
        ValueError: If there is no vote or sampling lacks a generator.
    """
    if len(votes) == 0:
        raise ValueError("no vote to aggregate")
    dist = np.bincount(np.asarray(votes, dtype=int), minlength=size).astype(float)
    dist /= dist.sum()
    if not sample:
        return int(np.argmax(dist)), dist
    if rng is None:
        raise ValueError("sampling a vote needs a random generator")
    return int(rng.choice(size, p=dist)), dist
